"""
Consolidated pLIN v4 results, generated only from the result files (no
hand-copied numbers). Re-run after any analysis changes.

Usage:
  python v4_results_summary.py
Output: output/backbone_v4/RESULTS_SUMMARY.md
"""

import json
import os

import pandas as pd

BASE_DIR = os.path.dirname(os.path.abspath(__file__))
V4 = os.path.join(BASE_DIR, "output", "backbone_v4")
EV = os.path.join(V4, "evaluation")


def md(df, floatfmt=3):
    df = df.copy()
    for c in df.columns:
        if df[c].dtype.kind == "f":
            df[c] = df[c].round(floatfmt)
    head = "| " + " | ".join(map(str, df.columns)) + " |"
    sep = "|" + "---|" * len(df.columns)
    body = ["| " + " | ".join("" if pd.isna(v) else str(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join([head, sep] + body)


def main():
    out = ["# pLIN v4: consolidated results", "",
           "Generated by `v4_results_summary.py` from the files in `output/backbone_v4/`. "
           "Pre-registration: `PREREGISTRATION.md` (deviations 1–4).", ""]

    pe = json.load(open(os.path.join(EV, "primary_endpoints.json")))
    out += ["## 1. Pre-registered primary endpoints (test half)", "",
            f"- L3 selected on calibration half: {pe['L3_selected']}; test pairs: {pe['test_pairs']}",
            f"- Endpoint 1 (related backbone, F1 v4 L3 − MOB-suite primary): "
            f"{pe['endpoint1_related_backbone_F1_v4L3_minus_MOBprimary']['difference']:+.3f} "
            f"[{pe['endpoint1_related_backbone_F1_v4L3_minus_MOBprimary']['lo']:+.3f}, "
            f"{pe['endpoint1_related_backbone_F1_v4L3_minus_MOBprimary']['hi']:+.3f}]",
            f"- Endpoint 2 (same lineage, F1 v4 L6 − MOB-suite secondary): "
            f"{pe['endpoint2_same_lineage_F1_v4L6_minus_MOBsecondary']['difference']:+.3f} "
            f"[{pe['endpoint2_same_lineage_F1_v4L6_minus_MOBsecondary']['lo']:+.3f}, "
            f"{pe['endpoint2_same_lineage_F1_v4L6_minus_MOBsecondary']['hi']:+.3f}]",
            f"- v4 incremental stability 100%: {pe['v4_incremental_stability_100pct']}",
            f"- **Gate 1 pass: {pe['gate1_pass']}**; endpoint 2 non-inferior: {pe['endpoint2_noninferior']}", ""]

    tm = pd.read_csv(os.path.join(EV, "test_metrics.tsv"), sep="\t")
    mg = pd.read_csv(os.path.join(EV, "mge_cluster_test_metrics.tsv"), sep="\t")
    keep = ["pLIN v3 L6", "pLIN v4 L1", "pLIN v4 L2", "pLIN v4 L3", "pLIN v4 L4", "pLIN v4 L5", "pLIN v4 L6",
            "MOB-suite primary", "MOB-suite secondary", "pling community", "pling subcommunity",
            "pLIN v4 L6 AND MOB-suite secondary"]
    acc = pd.concat([tm[tm.method.isin(keep)], mg[mg.method == "mge-cluster"]])
    for t in ("related_backbone", "same_lineage"):
        sub = acc[acc.truth == t][["method", "precision_w", "recall_w", "F1_w", "F1_w_lo", "F1_w_hi", "F1_unw",
                                   "plasmids_assigned"]]
        out += [f"## 2. Accuracy, test half, {t.replace('_', ' ')} (weighted; 95% bootstrap CI)", "", md(sub), ""]

    st4 = pd.read_csv(os.path.join(EV, "stability_v4.tsv"), sep="\t")
    st4 = st4.groupby(["mode", "level"]).agg(label_retained_min=("label_retained_pct", "min"),
                                             ARI_min=("ARI", "min")).reset_index()
    stp = pd.read_csv(os.path.join(EV, "stability_pling.tsv"), sep="\t")
    stm = pd.read_csv(os.path.join(EV, "stability_mge_cluster.tsv"), sep="\t")
    cols = ["tool", "mode", "level", "label_retained_pct", "pairs_split_pct", "pairs_merged", "ARI",
            "unassigned_before", "unassigned_after"]
    stm["level"] = "cluster"
    out += ["## 3. Label stability as the database grows", "",
            "pLIN v4 (2,000 evaluation plasmids; 3 snapshot sizes × 5 seeds; minimum over runs):", "", md(st4), "",
            "pling and mge-cluster (snapshot = seed-1 half):", "", md(pd.concat([stp[cols], stm[cols]])), ""]

    sp = pd.read_csv(os.path.join(V4, "speed", "speed_results.tsv"), sep="\t")
    out += ["## 4. Speed (same machine)", "", md(sp[["tool", "n_plasmids", "threads", "wall_s", "s_per_plasmid", "source"]], 4),
            "", "pling on all 2,000 evaluation plasmids (pipeline run, 12 threads, CPU shared with MOB-suite): "
            "1,735 s (from pling/pling.log timestamps).", ""]

    ob = pd.read_csv(os.path.join(EV, "outbreak_metrics.tsv"), sep="\t")
    out += ["## 5. Outbreak validation (74 plasmids, 27 studies; secondary, not pre-registered)", "", md(ob), ""]

    pt = pd.read_csv(os.path.join(EV, "ptu_agreement.tsv"), sep="\t")
    out += ["## 6. Agreement with published PTUs (Redondo-Salvo et al. 2020)", "", md(pt), ""]

    oh = json.load(open(os.path.join(V4, "onehealth", "summary.json")))
    ex = pd.read_csv(os.path.join(V4, "onehealth", "cross_sector_examples.tsv"), sep="\t")
    out += ["## 7. One Health (descriptive; PLSDB 2024_05_31_v2 metadata)", "", "```", json.dumps(oh, indent=2), "```", "",
            md(ex[ex.level == "L6"].head(10)), ""]

    open(os.path.join(V4, "RESULTS_SUMMARY.md"), "w").write("\n".join(out))
    print(f"wrote {os.path.join(V4, 'RESULTS_SUMMARY.md')}")


if __name__ == "__main__":
    main()
